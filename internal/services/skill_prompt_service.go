// scopeKind says which run an AGENTS.md is rendered for. A SKILL.md is
// shared by every run (scopeKindShared).
type scopeKind int

const (
	scopeKindShared scopeKind = iota
	scopeKindIncident
	scopeKindRequest
)

// renderMemoryRecallSection returns the recall instruction plus the scope's
// manifest rendered from the database ("global" for AGENTS.md, the skill name
// for SKILL.md), followed by the Record durable findings subsection (or the
// memory-off note). Returns "" when the service has no database.
func (s *SkillService) renderMemoryRecallSection(scope string) string {
	return s.renderMemoryRecallSectionFor(scope, scopeKindShared)
}

// renderMemoryRecallSectionFor is renderMemoryRecallSection with the run
// kind: an alert investigation gets the do-not-write instruction (the
// post-incident pass records its findings), request work gets the write
// guidance, a shared SKILL.md gets both in one neutral note.
func (s *SkillService) renderMemoryRecallSectionFor(scope string, kind scopeKind) string {
	if s.db == nil {
		return ""
	}
	manifest := RenderMemoryManifest(s.db, scope)

	var b strings.Builder
	b.WriteString("\n\n## Cross-incident Memory\n\n")
	b.WriteString(memoryRecallInstruction)
	b.WriteString("\n")

	if manifest != "" {
		b.WriteString("\n")
		b.WriteString(manifest)
		if !strings.HasSuffix(manifest, "\n") {
			b.WriteString("\n")
		}
	} else {
		b.WriteString("\n_No memories indexed for this scope yet._\n")
	}

	if !MemoryGenerationEnabled() {
		b.WriteString("\n### Recording findings is off\n\n")
		b.WriteString(memoryGenerationOffInstruction)
		b.WriteString("\n")
		return b.String()
	}
	b.WriteString("\n### Record durable findings\n\n")
	switch kind {
	case scopeKindIncident:
		b.WriteString(memoryIncidentRunInstruction)
	case scopeKindRequest:
		fmt.Fprintf(&b, memoryWriteInstructionTemplate, scope, scope)
	default:
		b.WriteString(memorySharedWriteNote)
		fmt.Fprintf(&b, memoryWriteInstructionTemplate, scope, scope)
	}
	b.WriteString("\n")
	return b.String()
}

// sshHasConfiguredHosts checks if the SSH tool instance has any configured hosts.
func sshHasConfiguredHosts(tool database.ToolInstance) bool {
	if tool.Settings == nil {
		return false
	}
	hostsData, ok := tool.Settings["ssh_hosts"]
	if !ok {
		return false
	}
	hostsJSON, err := json.Marshal(hostsData)
	if err != nil {
		return false
	}
	var hosts []map[string]interface{}
	if err := json.Unmarshal(hostsJSON, &hosts); err != nil {
		return false
	}
	for _, h := range hosts {
		if addr, _ := h["address"].(string); strings.TrimSpace(addr) != "" {
			return true
		}
	}
	return false
}

// sshAllHostsAllowWrite checks if ALL hosts in an SSH tool instance have allow_write_commands enabled.
// Returns false if any host is read-only (the default), if settings are missing, or if there are no hosts.
func sshAllHostsAllowWrite(tool database.ToolInstance) bool {
	if tool.Settings == nil {
		return false
	}
	hostsData, ok := tool.Settings["ssh_hosts"]
	if !ok {
		return false
	}
	hostsJSON, err := json.Marshal(hostsData)
	if err != nil {
		return false
	}
	var hosts []map[string]interface{}
	if err := json.Unmarshal(hostsJSON, &hosts); err != nil {
		return false
	}
	if len(hosts) == 0 {
		return false
	}
	hasValidHost := false
	for _, h := range hosts {
		// Skip placeholder rows with blank addresses (same filter as runtime)
		if addr, _ := h["address"].(string); strings.TrimSpace(addr) == "" {
			continue
		}
		hasValidHost = true
		allow, ok := h["allow_write_commands"].(bool)
		if !ok || !allow {
			return false
		}
	}
	return hasValidHost
}

